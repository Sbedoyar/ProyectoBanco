CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(254) UNIQUE NOT NULL,
 password_hash VARCHAR(512) NOT NULL
);
CREATE SEQUENCE IF NOT EXISTS account_number_seq START 100000000001;
CREATE TABLE IF NOT EXISTS account (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id BIGINT UNIQUE NOT NULL REFERENCES app_user(id),
 number VARCHAR(12) UNIQUE NOT NULL,
 balance NUMERIC(19,2) NOT NULL CHECK(balance >= 0),
 opened_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS opening_movement (
 account_id BIGINT PRIMARY KEY REFERENCES account(id),
 amount NUMERIC(19,2) NOT NULL CHECK(amount = 1000000.00),
 created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS bank_transfer (
 id UUID PRIMARY KEY,
 source_id BIGINT NOT NULL REFERENCES account(id),
 target_id BIGINT NOT NULL REFERENCES account(id),
 amount NUMERIC(19,2) NOT NULL CHECK(amount > 0),
 created_at TIMESTAMPTZ NOT NULL,
 idempotency_key UUID NOT NULL,
 UNIQUE(source_id,idempotency_key), CHECK(source_id <> target_id)
);
CREATE INDEX IF NOT EXISTS transfer_source_date ON bank_transfer(source_id,created_at);
CREATE INDEX IF NOT EXISTS transfer_target_date ON bank_transfer(target_id,created_at);
